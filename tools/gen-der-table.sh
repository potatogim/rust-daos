# Regenerate src/der_table.rs from a DAOS include directory, and
# abi/der2errno-<label>.txt from the daos_der2errno() of that tree.
#
# Usage: tools/gen-der-table.sh <include-dir> <label>
#   <include-dir>  for example /usr/include (daos-devel) or src/include of a tag
#   <label>        tag or package version the headers come from, for example v2.8.1

set -eu

[ $# -eq 2 ] || { echo "usage: $0 <include-dir> <label>" >&2; exit 2; }
inc=$1
label=$2
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/.." && pwd)
cc=${CC:-cc}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

cat >"$work/gen.c" <<'EOF'
#include <stdio.h>
#include <string.h>
#include <ctype.h>
#include <daos_errno.h>

static void
row(const char *name, int value, const char *desc)
{
	printf("    (%d, \"%s\", \"", value, name);
	for (const char *p = desc; *p; p++) {
		if (*p == '"' || *p == '\\')
			putchar('\\');
		putchar(*p);
	}
	printf("\"),\n");
}

static void
konst(const char *name, int value)
{
	/* DER_NO_PERM -> NO_PERM */
	printf("    pub const %s: DerCode = DerCode(%d);\n", name + 4, value);
}

#define ROW(n, d) row(#n, n, #d);
#define KONST(n, d) konst(#n, n);

int
main(int argc, char **argv)
{
	printf("// Copyright (c) 2026 Jihyeon Gim\n");
	printf("// SPDX-License-Identifier: MIT OR Apache-2.0\n");
	printf("// Portions transcribed from DAOS headers, BSD-2-Clause-Patent, see LICENSE-THIRD-PARTY\n");
	printf("//\n");
	printf("// Generated by tools/gen-der-table.sh from daos_errno.h (%s). Do not edit.\n\n", argv[1]);
	printf("//! DER error codes: value, name and description.\n\n");
	printf("use crate::error::DerCode;\n\n");
	printf("/// Label of the headers this table was generated from.\n");
	printf("#[allow(dead_code)]\n");
	printf("pub(crate) const DER_TABLE_SOURCE: &str = \"%s\";\n\n", argv[1]);
	printf("/// `(value, name, description)` for every DER code, in header order.\n");
	printf("pub(crate) static DER_TABLE: &[(i32, &str, &str)] = &[\n");
	D_FOREACH_GURT_ERR(ROW)
	D_FOREACH_DAOS_ERR(ROW)
	printf("];\n\n");
	printf("#[allow(missing_docs)]\n");
	printf("impl DerCode {\n");
	D_FOREACH_GURT_ERR(KONST)
	D_FOREACH_DAOS_ERR(KONST)
	printf("}\n");
	(void)argc;
	return 0;
}
EOF
"$cc" -std=gnu11 -Wall -Werror -I"$inc" -o "$work/gen" "$work/gen.c"
"$work/gen" "$label" >"$root/src/der_table.rs"
echo "wrote src/der_table.rs"

# daos_der2errno() is a static inline function in daos/common.h, which pulls
# in internal headers (and boost). Extract only that function's text and
# compile it next to daos_errno.h, to record its mapping as the fixture for
# the unit test of DerCode::to_errno.
awk '/^daos_der2errno\(int err\)/ { on = 1; print "static int" } on { print } on && /^}/ { exit }' \
	"$inc/daos/common.h" >"$work/der2errno.inc"
grep -q 'default:' "$work/der2errno.inc" || { echo "daos_der2errno not found in $inc/daos/common.h" >&2; exit 1; }
cat >"$work/fix.c" <<'EOF2'
#include <errno.h>
#include <stdio.h>
#include <daos_errno.h>
#define D_ERROR(...) ((void)0)
#include "der2errno.inc"
#define FIX(n, d) printf("%s %d\n", #n, daos_der2errno(-(n)));
int
main(void)
{
	D_FOREACH_GURT_ERR(FIX)
	D_FOREACH_DAOS_ERR(FIX)
	return 0;
}
EOF2
"$cc" -std=gnu11 -Wall -Werror -I"$work" -I"$inc" -o "$work/fix" "$work/fix.c"
"$work/fix" >"$root/abi/der2errno-$label.txt"
echo "wrote abi/der2errno-$label.txt"
